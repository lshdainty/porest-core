package com.porest.core.audit;

/**
 * 개인정보 접속기록의 "수행업무" 구분
 * <p>
 * 「개인정보의 안전성 확보조치 기준」 제8조가 접속기록에 요구하는 다섯 항목
 * (계정 · 접속일시 · 접속지 정보 · 처리한 정보주체 정보 · 수행업무) 중
 * <strong>수행업무</strong>에 해당합니다.
 *
 * <h3>무엇을 남기고 무엇을 남기지 않는가</h3>
 * <p>
 * 접속기록은 <strong>개인정보취급자가 타인의 개인정보를 처리한 기록</strong>입니다.
 * 정보주체 본인이 자기 정보를 조회하는 것은 취급자 접속이 아니므로 대상이 아닙니다.
 * 본인 데이터만 다루는 화면에까지 붙이면 기록이 노이즈로 덮여 정작 감사에 쓸 수 없습니다.
 *
 * @author porest
 * @see AuditAccess 기록 대상을 지정하는 어노테이션
 */
public enum AccessAction {

    /** 단건 조회 — 특정 정보주체의 개인정보를 열람 */
    READ,

    /** 목록 조회 — 여러 정보주체의 개인정보를 한 번에 열람 */
    LIST,

    /** 생성 */
    CREATE,

    /** 수정 */
    UPDATE,

    /** 삭제 */
    DELETE,

    /**
     * 출력·복사 — 파일 다운로드, 인쇄, 대량 내보내기
     * <p>
     * 고시 제13조(출력·복사 시 안전조치) 대상이기도 하므로 별도로 구분합니다.
     */
    EXPORT,

    /** 로그인 */
    LOGIN,

    /** 로그아웃 */
    LOGOUT
}
